def main():
    palettes = json.load(open(os.path.join(HERE, 'values.json')))['palettes']
    if '--ramps' in sys.argv:
        for p in palettes:
            c = p['cube']
            for row in 'FB':
                d, b = c[row + 'd'], c[row + 't']
                print(f"        ({d}, {b}, {cube_ramp(d, b)}),  // {p['name']} {row}")
        return 0
    outputs = ((TABLE, swift_table(palettes)), (GOLDENS, swift_goldens()))
    if '--check' in sys.argv:
        stale = [path for path, text in outputs if (open(path).read() if os.path.exists(path) else '') != text]
        for path in stale:
            print(f'{os.path.relpath(path, ROOT)} is stale: run python3 Tools/RowFillValues/generate.py')
        if not stale:
            print('RowFillTable.swift and RowFillRuleGoldens.swift are up to date')
        return 1 if stale else 0
    for path, text in outputs:
        open(path, 'w').write(text)
        print(f'wrote {os.path.relpath(path, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
